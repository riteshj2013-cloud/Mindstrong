def write_english_md(path: Path, title: str, chapter_id: str, lesson_steps: list[str], set_a, set_b, with_passages: bool):
    lines = [
        f"# Grade 7 English — {title}",
        "",
        "## Meta",
        f"- grade: 7",
        f"- subject: English",
        f"- chapter_id: {chapter_id}",
        "- sets: 2",
        "- items_per_set: 24",
        "",
        "## Interactive lesson outline",
    ]
    for i, step in enumerate(lesson_steps, 1):
        lines.append(f"- L{i}: {step}")
    lines.append("")
    if with_passages:
        lines.append("## Passage bank (for quizzes)")
        lines.append("")
        lines.append("### P1 — Community Garden")
        lines.append(PASSAGE_P1)
        lines.append("")
        lines.append("### P2 — Night Sky Volunteers")
        lines.append(PASSAGE_P2)
        lines.append("")
        lines.append("### P3 — Dawn Ferry")
        lines.append(PASSAGE_P3)
        lines.append("")
    for label, qs in (("A", set_a), ("B", set_b)):
        lines.append(f"## Set {label} — Practice quiz")
        lines.append("")
        for i, q in enumerate(qs, 1):
            # Strip embedded passage from stem for MD if present (keep full stem for TS)
            stem = q["stem"]
            lines.append(f"### Q{i:02d}")
            lines.append(f"- id: {chapter_id}-{label.lower()}-{i:02d}")
            lines.append("- stem: |")
            for ln in stem.split("\n"):
                lines.append(f"  {ln}")
            lines.append("- options:")
            for L, t in zip("ABCD", q["options"]):
                lines.append(f"  - {L}: {t}")
            lines.append(f"- answer: {q['answer']}")
            lines.append("- explanation: |")
            lines.append(f"  {q['explanation']}")
            lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def emit_hints(pack_name: str, const_name: str, items_by_chapter: list[list[dict]]):
    lines = [
        'import type { HintOverlay } from "./types";',
        "",
        f"/** Grade 7 {pack_name} item-specific hints (overlay) */",
        f"export const {const_name}: Record<string, HintOverlay> = {{",
    ]
    for items in items_by_chapter:
        for q in items:
            hint = q["_hint"].replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'  "{q["id"]}": ["{hint}"],')
    lines.append("};")
    lines.append("")
    (HINTS_DIR / f"g7-{pack_name.lower()}.ts").write_text("\n".join(lines), encoding="utf-8")


